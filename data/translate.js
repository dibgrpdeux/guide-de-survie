// Langue courante
window.currentLang = localStorage.getItem('enstp_lang') || 'ar';

// Fonction t() : retourne la traduction d'une clé
window.t = function(key) {
  const lang = window.currentLang || 'ar';
  const dict = window.translations[lang] || window.translations.ar;
  return dict[key] || window.translations.ar[key] || key;
};

// Fonction setLanguage() : change la langue et met à jour le DOM
window.setLanguage = function(lang) {
  window.currentLang = lang;
  localStorage.setItem('enstp_lang', lang);

  // Direction du document
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;

  // Mettre à jour tous les éléments avec data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = window.t(key);
    // Si l'élément contient des icônes, ne remplacer que le texte
    if (el.querySelector('i')) {
      const icon = el.querySelector('i');
      el.innerHTML = '';
      el.appendChild(icon);
      el.appendChild(document.createTextNode(' ' + val));
    } else {
      el.innerText = val;
    }
  });

  // Mettre à jour les placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = window.t(el.getAttribute('data-i18n-placeholder'));
  });

  // Mettre à jour les titres (attribut title)
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = window.t(el.getAttribute('data-i18n-title'));
  });

  // Mettre à jour les boutons de langue
  document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.remove('active'));
  const activeBtn = document.getElementById('btn-' + lang);
  if (activeBtn) activeBtn.classList.add('active');

  // Émettre un événement pour que les scripts des pages réagissent
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
};

// Au chargement, appliquer la langue sauvegardée
window.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('enstp_lang') || 'ar';
  setTimeout(() => window.setLanguage(saved), 50);
});
